/**
 * The .sql file is the artefact Sprint 1 gets handed. The browser cannot
 * read it off disk, so this mirrors it into a TypeScript module. A test
 * (`migrations.test.ts`) fails if the two ever drift.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sql = readFileSync(join(root, 'migrations/001_init.sql'), 'utf8')

writeFileSync(
  join(root, 'src/migrations.ts'),
  `/* GENERATED by scripts/generate-migration-module.mjs — do not edit.\n * Source of truth: migrations/001_init.sql\n */\n\nexport const MIGRATION_001_INIT = ${JSON.stringify(sql)}\n\nexport interface Migration {\n  name: string\n  sql: string\n}\n\nexport const MIGRATIONS: Migration[] = [\n  { name: '001_init', sql: MIGRATION_001_INIT },\n]\n`,
)
console.log('wrote src/migrations.ts')
